import {test,expect} from '@playwright/test'
async function open(page:any,name:string){await page.getByRole('button',{name:'打开聊天历史'}).click();await page.locator('.drawer-shortcuts').getByRole('button',{name,exact:true}).click()}
test('four sidebar destinations and reminder management',async({page})=>{
 await page.goto('/')
 await open(page,'我的提醒')
 await page.getByRole('button',{name:'添加提醒',exact:true}).click()
 await page.getByLabel('提醒什么').fill('给女儿打电话')
 await page.getByLabel('重复').selectOption('daily')
 await page.getByLabel('时间').fill('09:00')
 await page.getByRole('button',{name:'保存提醒',exact:true}).click()
 await expect(page.locator('.reminder-card')).toContainText('给女儿打电话')
 await page.reload();await open(page,'我的提醒')
 await expect(page.locator('.reminder-card')).toContainText('09:00')
 await page.getByRole('button',{name:'修改',exact:true}).click()
 await page.getByRole('button',{name:'暂停提醒',exact:true}).click()
 await expect(page.locator('.reminder-card')).toHaveCount(0)
 await page.getByRole('button',{name:'已暂停',exact:true}).click()
 await expect(page.locator('.reminder-card')).toHaveCount(1)
 await open(page,'我的拾光');await expect(page.locator('.memory-library')).toBeVisible()
 await open(page,'我的亲友');await expect(page.getByRole('tab',{name:'家人',exact:true})).toHaveAttribute('aria-selected','true')
 await open(page,'帮我看看');await page.getByRole('button',{name:'看看通知示例',exact:true}).click()
 await expect(page.getByRole('button',{name:'读给我听',exact:true})).toBeVisible()
 await page.getByRole('button',{name:'从相册选',exact:true}).click()
 await page.locator('.help-look input[type=file]').setInputFiles('public/images/t-p03.jpg')
 await expect(page.locator('.look-photo')).toBeVisible()
 await expect(page.getByRole('button',{name:'读给我听',exact:true})).toHaveCount(0)
})
