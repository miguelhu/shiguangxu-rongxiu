import {test,expect} from '@playwright/test'
test('article upload persists title, body and source in the article category',async({page})=>{
 await page.goto('/app-plus/')
 await page.getByRole('button',{name:'添加照片或录音'}).click()
 await page.getByRole('button',{name:'文章 · 上传或粘贴'}).click()
 await page.locator('.article-editor input[type=file]').setInputFiles({name:'读到的一篇文章.txt',mimeType:'text/plain',buffer:Buffer.from('今天读到一篇关于四季的文章。\n春天的花开了，值得慢慢欣赏。')})
 await expect(page.getByLabel('文章标题')).toHaveValue('读到的一篇文章')
 await page.getByLabel('作者或来源（选填）').fill('四季散文集')
 await page.getByRole('button',{name:'收藏到我的拾光'}).click()
 await page.getByRole('group',{name:'内容分类'}).getByRole('button',{name:/文章/}).click()
 await expect(page.locator('.library-card')).toHaveCount(1)
 await expect(page.locator('.library-card')).toContainText('四季散文集')
 await page.getByRole('button',{name:'展开阅读'}).click()
 await expect(page.locator('.article-body')).toContainText('春天的花开了')
 await page.getByRole('group',{name:'内容分类'}).getByRole('button',{name:/照片/}).click()
 await expect(page.locator('.library-card')).toHaveCount(0)
 await page.reload()
 await page.getByRole('button',{name:'翻翻我的拾光'}).click()
 await expect(page.locator('.library-card')).toHaveCount(1)
 await expect(page.locator('.library-card')).toContainText('读到的一篇文章')
})
