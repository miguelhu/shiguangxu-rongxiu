import {test,expect} from '@playwright/test'
test('new conversations rotate prompts and keep prior chat available',async({page})=>{
 await page.goto('/app-plus/')
 await expect(page.locator('.plus-nav')).toHaveCount(0)
 await expect(page.getByRole('navigation',{name:'主导航'}).getByRole('button',{name:'消息',exact:true})).toBeVisible()
 const camera=await page.getByRole('button',{name:'拍照发日常'}).boundingBox();expect(camera!.width).toBeGreaterThanOrEqual(50)
 const old=await page.locator('.welcome-prompts').textContent()
 await page.getByRole('button',{name:'换几个话题'}).click()
 expect(await page.locator('.welcome-prompts').textContent()).not.toEqual(old)
 await page.getByRole('button',{name:'切换打字'}).click()
 await page.getByRole('textbox',{name:'给小叙留言'}).fill('今天和老同事一起吃饭')
 await page.getByRole('button',{name:'发送问题'}).click()
 await page.getByRole('button',{name:'打开聊天历史'}).click()
 await page.getByRole('button',{name:'新话题',exact:true}).click()
 await expect(page.locator('.agent-home:visible .agent-message.user')).toHaveCount(0)
 await page.getByRole('button',{name:'打开聊天历史'}).click()
 await page.locator('.history-item').filter({hasText:'今天和老同事一起吃饭'}).click()
 await expect(page.locator('.agent-home:visible .agent-message.user')).toContainText('今天和老同事一起吃饭')
})
